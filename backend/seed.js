const cargarDatos = async () => {
  try {
    await conectarDB();
    for (const usuario of usuariosDePrueba) {
      const password = await bcrypt.hash(usuario.password, 10);
      await User.updateOne({ email: usuario.email }, { $set: { ...usuario, password } }, { upsert: true });
    }
    await Destino.updateMany({ activo: { $exists: false } }, { $set: { activo: false } });
    for (const destino of destinosDePrueba) {
      await Destino.updateOne({ nombre: destino.nombre }, { $set: destino }, { upsert: true });
    }
    console.log('Usuarios y catálogo RallyTraver creados o actualizados correctamente.');
  } catch (error) {
    console.error('No se pudieron cargar los datos:', error.message);
    process.exitCode = 1;
  } finally {
    await mongoose.connection.close();
  }
};

cargarDatos();
